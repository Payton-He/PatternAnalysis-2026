"""VAE and WGAN-GP models for 256x128 single-channel hip MRI slices.

Torch only (numpy is not allowed in this file).
Images are expected in [0, 1] for the VAE.
"""
import torch
import torch.nn as nn


def _bottleneck_size(img_size):
    """Return the (height, width) of the smallest feature map in the network.

    The encoder halves the spatial size 4 times (2**4 = 16), so both image
    dimensions must be divisible by 16.

    Args:
        img_size: (H, W) of the input images, e.g. (256, 128).

    Returns:
        (H // 16, W // 16), e.g. (16, 8) for 256x128 input.
    """
    H, W = img_size
    assert H % 16 == 0 and W % 16 == 0, "H and W must be divisible by 16"
    return H // 16, W // 16


def _down(i, o, norm="batch"):
    """Encoder block that halves the spatial size: Conv -> Norm -> LeakyReLU.

    Conv2d(kernel=4, stride=2, padding=1) maps (H, W) -> (H/2, W/2), so it
    acts as a learned downsampling layer.

    Args:
        i: number of input channels.
        o: number of output channels.
        norm: "batch" for BatchNorm2d, "layer" for GroupNorm(1, o)
            (equivalent to LayerNorm over C, H, W), or anything else for no
            normalisation.
    """
    if norm == "batch":
        n = nn.BatchNorm2d(o)
    elif norm == "layer":
        n = nn.GroupNorm(1, o)  # one group = normalise over (C, H, W) per sample
    else:
        n = nn.Identity()       # no normalisation
    return nn.Sequential(nn.Conv2d(i, o, 4, 2, 1), n, nn.LeakyReLU(0.2))


def _up(i, o):
    """Decoder block that doubles the spatial size: ConvTranspose -> BatchNorm -> ReLU.

    ConvTranspose2d(kernel=4, stride=2, padding=1) maps (H, W) -> (2H, 2W),
    mirroring what _down does.

    Args:
        i: number of input channels.
        o: number of output channels.
    """
    return nn.Sequential(nn.ConvTranspose2d(i, o, 4, 2, 1), nn.BatchNorm2d(o), nn.ReLU())


class VAE(nn.Module):
    """Convolutional variational autoencoder.

    The encoder maps an image to a Gaussian distribution over a latent vector
    (a mean and a log-variance). A latent vector z is sampled from it and the
    decoder reconstructs the image from z. Training (in train.py) combines a
    reconstruction loss with a KL term that pulls the distribution towards
    N(0, I), so new images can be generated by decoding z ~ N(0, I).

    Shapes for the default 256x128 input (channels x height x width):
        input       1 x 256 x 128
        encoder     256 x 16 x 8      (four stride-2 blocks)
        flattened   32768
        latent z    128
        output      1 x 256 x 128, values in [0, 1] (Sigmoid)

    Args:
        in_channels: number of image channels (1 for greyscale MRI).
        img_size: (H, W) of the input; both must be divisible by 16.
        latent_dim: size of the latent vector z.
        base: channel width of the first conv layer; each later layer doubles it
            (32 -> 64 -> 128 -> 256).
    """

    def __init__(self, in_channels=1, img_size=(256, 128), latent_dim=128, base=32):
        super().__init__()
        self.h, self.w = _bottleneck_size(img_size)  # bottleneck map size, e.g. 16 x 8
        self.feat = base * 8                         # channels at the bottleneck, e.g. 256
        self.latent_dim = latent_dim

        # Encoder: 1x256x128 -> 32x128x64 -> 64x64x32 -> 128x32x16 -> 256x16x8
        self.encoder = nn.Sequential(
            _down(in_channels, base), _down(base, base * 2),
            _down(base * 2, base * 4), _down(base * 4, base * 8),
        )

        # Number of values after flattening the bottleneck, e.g. 256 * 16 * 8 = 32768
        flat = self.feat * self.h * self.w

        self.fc_mu = nn.Linear(flat, latent_dim)      # flattened features -> mean of q(z|x)
        self.fc_logvar = nn.Linear(flat, latent_dim)  # flattened features -> log-variance of q(z|x)
        self.fc_dec = nn.Linear(latent_dim, flat)     # z -> flattened features for the decoder

        # Decoder: 256x16x8 -> 128x32x16 -> 64x64x32 -> 32x128x64 -> 1x256x128
        # The final Sigmoid keeps outputs in [0, 1], matching the data range.
        self.decoder = nn.Sequential(
            _up(base * 8, base * 4), _up(base * 4, base * 2), _up(base * 2, base),
            nn.ConvTranspose2d(base, in_channels, 4, 2, 1), nn.Sigmoid(),
        )

    def encode(self, x):
        """Map images to the parameters of the latent distribution.

        Args:
            x: batch of images, shape (B, C, H, W), values in [0, 1].

        Returns:
            mu: (B, latent_dim) mean of the latent distribution.
            logvar: (B, latent_dim) log-variance, clamped to [-10, 10] so that
                exp(logvar) cannot overflow and produce NaNs.
        """
        h = self.encoder(x).flatten(1)  # (B, 256, 16, 8) -> (B, 32768)
        return self.fc_mu(h), self.fc_logvar(h).clamp(-10.0, 10.0)

    def reparameterize(self, mu, logvar):
        """Sample z = mu + sigma * eps, with eps ~ N(0, I) (the reparameterisation trick).

        Sampling directly from N(mu, sigma^2) would block gradients. Moving the
        randomness into eps, which has no learnable parameters, lets gradients
        flow back through mu and logvar to the encoder.

        Args:
            mu: (B, latent_dim) means.
            logvar: (B, latent_dim) log-variances.

        Returns:
            z: (B, latent_dim) sampled latent vectors.
        """
        std = torch.exp(0.5 * logvar)  # sigma = sqrt(variance) = exp(logvar / 2)
        return mu + torch.randn_like(mu) * std

    def decode(self, z):
        """Map latent vectors to images.

        Args:
            z: (B, latent_dim) latent vectors.

        Returns:
            (B, C, H, W) images with values in [0, 1].
        """
        # Expand z to the flattened bottleneck, then reshape to a feature map.
        # The -1 lets the batch size vary.
        return self.decoder(self.fc_dec(z).view(-1, self.feat, self.h, self.w))

    def forward(self, x):
        """Full pass used in training: encode, sample z, decode.

        Args:
            x: (B, C, H, W) images in [0, 1].

        Returns:
            recon: (B, C, H, W) reconstruction of x.
            mu, logvar: (B, latent_dim) each, needed for the KL term in the loss.
        """
        mu, logvar = self.encode(x)
        return self.decode(self.reparameterize(mu, logvar)), mu, logvar

    @torch.no_grad()
    def sample(self, n):
        """Generate n new images by decoding z drawn from the prior N(0, I).

        Call model.eval() first so BatchNorm uses its running statistics.

        Args:
            n: number of images to generate.

        Returns:
            (n, C, H, W) generated images in [0, 1], on the model's device.
        """
        device = next(self.parameters()).device  # put the noise on the same device as the model
        z = torch.randn(n, self.latent_dim, device=device)
        return self.decode(z)

