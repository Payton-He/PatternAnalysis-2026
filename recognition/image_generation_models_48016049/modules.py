"""Models for 256x128 single-channel hip MRI slices: a baseline VAE, a VQ-VAE and its code prior.

    VAE        continuous latent vector; the baseline.
    VQVAE      discrete latent grid of codebook indices; reconstructs images.
    CodePrior  autoregressive transformer over the VQ-VAE's code grid; samples new grids,
               which the VQ-VAE decoder turns into new images.

Torch only (numpy is not allowed in this file).
Images are expected in [0, 1].
"""
import torch
import torch.nn as nn
import torch.nn.functional as F


def _bottleneck_size(img_size):
    """Return the (height, width) of the smallest feature map in the network.

    The encoder halves the spatial size 4 times (2**4 = 16), so both image
    dimensions must be divisible by 16.

    Args:
        img_size: (H, W) of the input images, e.g. (256, 128).

    Returns:
        (H // 16, W // 16), e.g. (16, 8) for 256x128 input.
    """
    H, W = img_size
    assert H % 16 == 0 and W % 16 == 0, "H and W must be divisible by 16"
    return H // 16, W // 16


def _down(i, o, norm="batch"):
    """Encoder block that halves the spatial size: Conv -> Norm -> LeakyReLU.

    Conv2d(kernel=4, stride=2, padding=1) maps (H, W) -> (H/2, W/2), so it
    acts as a learned downsampling layer.

    Args:
        i: number of input channels.
        o: number of output channels.
        norm: "batch" for BatchNorm2d, "layer" for GroupNorm(1, o)
            (equivalent to LayerNorm over C, H, W), or anything else for no
            normalisation.
    """
    if norm == "batch":
        n = nn.BatchNorm2d(o)
    elif norm == "layer":
        n = nn.GroupNorm(1, o)  # one group = normalise over (C, H, W) per sample
    else:
        n = nn.Identity()       # no normalisation
    return nn.Sequential(nn.Conv2d(i, o, 4, 2, 1), n, nn.LeakyReLU(0.2))


def _up(i, o):
    """Decoder block that doubles the spatial size: ConvTranspose -> BatchNorm -> ReLU.

    ConvTranspose2d(kernel=4, stride=2, padding=1) maps (H, W) -> (2H, 2W),
    mirroring what _down does.

    Args:
        i: number of input channels.
        o: number of output channels.
    """
    return nn.Sequential(nn.ConvTranspose2d(i, o, 4, 2, 1), nn.BatchNorm2d(o), nn.ReLU())


class VAE(nn.Module):
    """Convolutional variational autoencoder.

    The encoder maps an image to a Gaussian distribution over a latent vector
    (a mean and a log-variance). A latent vector z is sampled from it and the
    decoder reconstructs the image from z. Training (in train.py) combines a
    reconstruction loss with a KL term that pulls the distribution towards
    N(0, I), so new images can be generated by decoding z ~ N(0, I).

    Shapes for the default 256x128 input (channels x height x width):
        input       1 x 256 x 128
        encoder     256 x 16 x 8      (four stride-2 blocks)
        flattened   32768
        latent z    128
        output      1 x 256 x 128, values in [0, 1] (Sigmoid)

    Args:
        in_channels: number of image channels (1 for greyscale MRI).
        img_size: (H, W) of the input; both must be divisible by 16.
        latent_dim: size of the latent vector z.
        base: channel width of the first conv layer; each later layer doubles it
            (32 -> 64 -> 128 -> 256).
    """

    def __init__(self, in_channels=1, img_size=(256, 128), latent_dim=128, base=32):
        super().__init__()
        self.h, self.w = _bottleneck_size(img_size)  # bottleneck map size, e.g. 16 x 8
        self.feat = base * 8                         # channels at the bottleneck, e.g. 256
        self.latent_dim = latent_dim

        # Encoder: 1x256x128 -> 32x128x64 -> 64x64x32 -> 128x32x16 -> 256x16x8
        self.encoder = nn.Sequential(
            _down(in_channels, base), _down(base, base * 2),
            _down(base * 2, base * 4), _down(base * 4, base * 8),
        )

        # Number of values after flattening the bottleneck, e.g. 256 * 16 * 8 = 32768
        flat = self.feat * self.h * self.w

        self.fc_mu = nn.Linear(flat, latent_dim)      # flattened features -> mean of q(z|x)
        self.fc_logvar = nn.Linear(flat, latent_dim)  # flattened features -> log-variance of q(z|x)
        self.fc_dec = nn.Linear(latent_dim, flat)     # z -> flattened features for the decoder

        # Decoder: 256x16x8 -> 128x32x16 -> 64x64x32 -> 32x128x64 -> 1x256x128
        # The final Sigmoid keeps outputs in [0, 1], matching the data range.
        self.decoder = nn.Sequential(
            _up(base * 8, base * 4), _up(base * 4, base * 2), _up(base * 2, base),
            nn.ConvTranspose2d(base, in_channels, 4, 2, 1), nn.Sigmoid(),
        )

    def encode(self, x):
        """Map images to the parameters of the latent distribution.

        Args:
            x: batch of images, shape (B, C, H, W), values in [0, 1].

        Returns:
            mu: (B, latent_dim) mean of the latent distribution.
            logvar: (B, latent_dim) log-variance, clamped to [-10, 10] so that
                exp(logvar) cannot overflow and produce NaNs.
        """
        h = self.encoder(x).flatten(1)  # (B, 256, 16, 8) -> (B, 32768)
        return self.fc_mu(h), self.fc_logvar(h).clamp(-10.0, 10.0)

    def reparameterize(self, mu, logvar):
        """Sample z = mu + sigma * eps, with eps ~ N(0, I) (the reparameterisation trick).

        Sampling directly from N(mu, sigma^2) would block gradients. Moving the
        randomness into eps, which has no learnable parameters, lets gradients
        flow back through mu and logvar to the encoder.

        Args:
            mu: (B, latent_dim) means.
            logvar: (B, latent_dim) log-variances.

        Returns:
            z: (B, latent_dim) sampled latent vectors.
        """
        std = torch.exp(0.5 * logvar)  # sigma = sqrt(variance) = exp(logvar / 2)
        return mu + torch.randn_like(mu) * std

    def decode(self, z):
        """Map latent vectors to images.

        Args:
            z: (B, latent_dim) latent vectors.

        Returns:
            (B, C, H, W) images with values in [0, 1].
        """
        # Expand z to the flattened bottleneck, then reshape to a feature map.
        # The -1 lets the batch size vary.
        return self.decoder(self.fc_dec(z).view(-1, self.feat, self.h, self.w))

    def forward(self, x):
        """Full pass used in training: encode, sample z, decode.

        Args:
            x: (B, C, H, W) images in [0, 1].

        Returns:
            recon: (B, C, H, W) reconstruction of x.
            mu, logvar: (B, latent_dim) each, needed for the KL term in the loss.
        """
        mu, logvar = self.encode(x)
        return self.decode(self.reparameterize(mu, logvar)), mu, logvar

    @torch.no_grad()
    def sample(self, n):
        """Generate n new images by decoding z drawn from the prior N(0, I).

        Call model.eval() first so BatchNorm uses its running statistics.

        Args:
            n: number of images to generate.

        Returns:
            (n, C, H, W) generated images in [0, 1], on the model's device.
        """
        device = next(self.parameters()).device  # put the noise on the same device as the model
        z = torch.randn(n, self.latent_dim, device=device)
        return self.decode(z)


# ================================================================ VQ-VAE
# An autoencoder whose bottleneck is DISCRETE: each cell of the encoder's feature map is
# replaced by the closest of K learned "codebook" vectors. An image becomes a small grid of
# integers (32 x 16 codes for a 256 x 128 slice), and the decoder rebuilds the image from the
# codebook vectors those integers point to. Reconstruction is direct (encode -> quantize ->
# decode), which is what the SSIM > 0.6 target measures. New images are made later by
# sampling code grids from a separate prior model (see the prior section).


class VectorQuantizer(nn.Module):
    """Snap each latent vector to its nearest codebook entry (vector quantization).

    The codebook is not trained by gradient descent. Each entry is instead an exponential
    moving average (EMA) of the encoder vectors assigned to it, which is more stable than the
    original codebook loss. Two safeguards fight "codebook collapse" (the discrete form of mode
    collapse, where only a few codes ever get used):
        - the codebook is initialised from real encoder outputs in the first training step;
        - a code whose EMA usage falls below `reset_threshold` is replaced by a random encoder
          vector from the current batch ("dead code reset").

    Gradients cannot pass through the nearest-neighbour lookup, so the straight-through
    estimator is used: the forward pass outputs the quantized vectors, while the backward pass
    copies the gradient from the decoder input straight onto the encoder output.

    Args:
        num_codes: codebook size K (number of distinct codes).
        dim: size of each code vector.
        beta: weight of the commitment loss, which pulls encoder outputs towards their codes.
        decay: EMA decay for the codebook (closer to 1 = slower, smoother updates).
        reset_threshold: EMA usage (vectors per batch) below which a code counts as dead.
    """

    def __init__(self, num_codes=512, dim=64, beta=0.25, decay=0.99, eps=1e-5, reset_threshold=0.1):
        super().__init__()
        self.num_codes, self.dim, self.beta = num_codes, dim, beta
        self.decay, self.eps, self.reset_threshold = decay, eps, reset_threshold
        embed = torch.randn(num_codes, dim)
        # Buffers are saved in the checkpoint but are not trained by the optimiser.
        self.register_buffer("embed", embed)                         # (K, D) the codebook
        self.register_buffer("embed_avg", embed.clone())             # EMA of the sum of assigned vectors
        self.register_buffer("cluster_size", torch.ones(num_codes))  # EMA of how often each code is used
        self.register_buffer("initted", torch.zeros((), dtype=torch.bool))

    def forward(self, z):
        """Quantize a batch of feature maps.

        Args:
            z: (B, D, H, W) encoder output.

        Returns:
            quantized: (B, D, H, W) codebook vectors with straight-through gradients.
            commit_loss: scalar, beta * mean squared distance between z and its codes.
            idx: (B, H, W) integer code index of every cell.
            perplexity: scalar, effective number of codes used in this batch
                (K = all used equally, 1 = a single code; a falling value warns of collapse).
        """
        B, D, H, W = z.shape
        flat = z.permute(0, 2, 3, 1).reshape(-1, D)                  # (B*H*W, D) one row per cell

        if self.training and not bool(self.initted):                 # first step: start the codebook on real data
            pick = torch.randint(0, len(flat), (self.num_codes,), device=flat.device)
            self.embed.copy_(flat.detach()[pick])
            self.embed_avg.copy_(self.embed)
            self.initted.fill_(True)

        # Squared distance from every vector to every code: |x|^2 - 2 x.e + |e|^2
        dist = flat.pow(2).sum(1, keepdim=True) - 2 * flat @ self.embed.t() + self.embed.pow(2).sum(1)[None]
        idx = dist.argmin(1)                                         # nearest code per vector
        quantized = F.embedding(idx, self.embed)                     # (B*H*W, D)

        counts = torch.bincount(idx, minlength=self.num_codes).to(flat.dtype)
        if self.training:
            with torch.no_grad():
                self.cluster_size.mul_(self.decay).add_(counts, alpha=1 - self.decay)
                sums = torch.zeros_like(self.embed).index_add_(0, idx, flat.detach())
                self.embed_avg.mul_(self.decay).add_(sums, alpha=1 - self.decay)

                dead = self.cluster_size < self.reset_threshold      # replace unused codes with real vectors
                if bool(dead.any()):
                    pick = torch.randint(0, len(flat), (int(dead.sum()),), device=flat.device)
                    self.embed_avg[dead] = flat.detach()[pick]
                    self.cluster_size[dead] = 1.0

                n = self.cluster_size.sum()                          # Laplace smoothing avoids dividing by ~0
                size = (self.cluster_size + self.eps) / (n + self.num_codes * self.eps) * n
                self.embed.copy_(self.embed_avg / size.unsqueeze(1))

        commit_loss = self.beta * F.mse_loss(flat, quantized.detach())
        quantized = flat + (quantized - flat).detach()               # straight-through estimator
        probs = counts / counts.sum()
        perplexity = torch.exp(-(probs * torch.log(probs + 1e-10)).sum())
        return quantized.view(B, H, W, D).permute(0, 3, 1, 2), commit_loss, idx.view(B, H, W), perplexity

    def lookup(self, idx):
        """Turn a grid of code indices (B, H, W) into feature maps (B, D, H, W)."""
        return F.embedding(idx, self.embed).permute(0, 3, 1, 2)


class _ResBlock(nn.Module):
    """Residual block: x + Conv1x1(ReLU(Conv3x3(ReLU(x)))). Adds depth without changing the shape."""

    def __init__(self, ch, hidden):
        super().__init__()
        self.net = nn.Sequential(nn.ReLU(), nn.Conv2d(ch, hidden, 3, 1, 1), nn.ReLU(), nn.Conv2d(hidden, ch, 1))

    def forward(self, x):
        return x + self.net(x)


class VQVAE(nn.Module):
    """Vector-quantised autoencoder for 256x128 single-channel slices.

    Shapes for the default 256x128 input (channels x height x width):
        input         1 x 256 x 128
        encoder       128 x 32 x 16     (three stride-2 convolutions, 8x smaller)
        pre-quant      64 x 32 x 16     (1x1 conv to the code dimension)
        code grid           32 x 16     (512 integers, each in [0, num_codes))
        decoder out    1 x 256 x 128    values in [0, 1] (Sigmoid)

    Args:
        in_channels: image channels (1 for greyscale MRI).
        img_size: (H, W) of the input; both must be divisible by 8.
        hidden: channel width of the encoder and decoder.
        res_hidden: channel width inside the residual blocks.
        num_res: residual blocks in the encoder and in the decoder.
        num_codes: codebook size K.
        code_dim: size of each code vector.
        beta: commitment-loss weight (see VectorQuantizer).
        decay: EMA decay of the codebook (see VectorQuantizer).
    """

    def __init__(self, in_channels=1, img_size=(256, 128), hidden=128, res_hidden=64, num_res=2,
                 num_codes=512, code_dim=64, beta=0.25, decay=0.99):
        super().__init__()
        H, W = img_size
        assert H % 8 == 0 and W % 8 == 0, "H and W must be divisible by 8"
        self.grid = (H // 8, W // 8)                                 # size of the code grid, e.g. (32, 16)
        self.num_codes = num_codes

        # Encoder: 1x256x128 -> 64x128x64 -> 128x64x32 -> 128x32x16 -> residual blocks -> 64x32x16
        self.encoder = nn.Sequential(
            nn.Conv2d(in_channels, hidden // 2, 4, 2, 1), nn.ReLU(),
            nn.Conv2d(hidden // 2, hidden, 4, 2, 1), nn.ReLU(),
            nn.Conv2d(hidden, hidden, 4, 2, 1),
            *[_ResBlock(hidden, res_hidden) for _ in range(num_res)],
            nn.ReLU(), nn.Conv2d(hidden, code_dim, 1),
        )
        self.vq = VectorQuantizer(num_codes, code_dim, beta, decay)
        # Decoder mirrors the encoder: 64x32x16 -> 128x32x16 -> residual blocks -> upsample three times
        self.decoder = nn.Sequential(
            nn.Conv2d(code_dim, hidden, 3, 1, 1),
            *[_ResBlock(hidden, res_hidden) for _ in range(num_res)],
            nn.ReLU(), nn.ConvTranspose2d(hidden, hidden // 2, 4, 2, 1), nn.ReLU(),
            nn.ConvTranspose2d(hidden // 2, hidden // 2, 4, 2, 1), nn.ReLU(),
            nn.ConvTranspose2d(hidden // 2, in_channels, 4, 2, 1), nn.Sigmoid(),
        )

    def forward(self, x):
        """Full pass used in training: encode, quantize, decode.

        Args:
            x: (B, C, H, W) images in [0, 1].

        Returns:
            recon: (B, C, H, W) reconstruction of x.
            commit_loss: scalar commitment loss (add to the reconstruction loss).
            idx: (B, H/8, W/8) code indices.
            perplexity: scalar, effective number of codes in use in this batch.
        """
        q, commit_loss, idx, perplexity = self.vq(self.encoder(x))
        return self.decoder(q), commit_loss, idx, perplexity

    @torch.no_grad()
    def encode_indices(self, x):
        """Images -> integer code grids (B, H/8, W/8). Used to train the prior and to audit code usage."""
        return self.vq(self.encoder(x))[2]

    @torch.no_grad()
    def decode_indices(self, idx):
        """Integer code grids (B, H/8, W/8) -> images (B, C, H, W) in [0, 1]. Used to turn sampled codes into images."""
        return self.decoder(self.vq.lookup(idx))

# ================================================================ Code prior
# A VQ-VAE only reconstructs. To generate NEW images, a second model learns which code grids
# real images produce, then samples new grids that the VQ-VAE decoder turns into images.


class CodePrior(nn.Module):
    """Autoregressive transformer over a VQ-VAE code grid, read in raster order (row by row).

    At every position it predicts a distribution over the next code from all codes before it.
    The input is the grid shifted right by one place, with a special start token in front, and a
    causal mask stops a position from seeing later ones. Position is encoded as separate learned
    row and column embeddings, so the model knows where in the image each code sits.

    Args:
        num_codes: codebook size K of the VQ-VAE (token ids are 0..K-1; K is the start token).
        grid: (rows, cols) of the code grid, e.g. (32, 16).
        dim: transformer width.
        layers: number of transformer layers.
        heads: attention heads (must divide dim).
        dropout: dropout rate; the main defence against memorising the training grids.
    """

    def __init__(self, num_codes=512, grid=(32, 16), dim=256, layers=6, heads=8, dropout=0.1):
        super().__init__()
        self.num_codes, self.grid = num_codes, tuple(grid)
        L = self.grid[0] * self.grid[1]                              # sequence length, e.g. 512
        self.seq_len = L
        self.tok = nn.Embedding(num_codes + 1, dim)                  # +1 for the start token
        self.pos_row = nn.Embedding(self.grid[0], dim)
        self.pos_col = nn.Embedding(self.grid[1], dim)
        block = nn.TransformerEncoderLayer(dim, heads, 4 * dim, dropout, activation="gelu",
                                           batch_first=True, norm_first=True)
        self.blocks = nn.TransformerEncoder(block, layers, enable_nested_tensor=False)
        self.norm = nn.LayerNorm(dim)
        self.head = nn.Linear(dim, num_codes)
        pos = torch.arange(L)
        self.register_buffer("rows", pos // self.grid[1], persistent=False)   # row of each sequence position
        self.register_buffer("cols", pos % self.grid[1], persistent=False)    # column of each position
        # Causal mask: -inf above the diagonal so position t cannot attend to positions after t
        self.register_buffer("mask", torch.full((L, L), float("-inf")).triu(1), persistent=False)

    def forward(self, tokens):
        """Next-code logits for every position.

        Args:
            tokens: (B, T) long tensor, T <= seq_len, starting with the start token.

        Returns:
            (B, T, num_codes) logits; entry t scores the code that comes AFTER position t.
        """
        T = tokens.size(1)
        x = self.tok(tokens) + self.pos_row(self.rows[:T]) + self.pos_col(self.cols[:T])
        x = self.blocks(x, mask=self.mask[:T, :T])
        return self.head(self.norm(x))

    def loss(self, idx):
        """Mean cross-entropy (nats per code) of a batch of code grids.

        Args:
            idx: (B, H, W) long tensor of code indices from VQVAE.encode_indices.
        """
        flat = idx.flatten(1)                                        # (B, L) raster order
        start = torch.full((flat.size(0), 1), self.num_codes, dtype=flat.dtype, device=flat.device)
        logits = self(torch.cat([start, flat[:, :-1]], dim=1))       # shift right: predict code t from codes < t
        return F.cross_entropy(logits.reshape(-1, self.num_codes), flat.reshape(-1))

    @torch.no_grad()
    def sample(self, n, temperature=1.0, top_k=None):
        """Draw n new code grids, one code at a time.

        Call prior.eval() first so dropout is off.

        The sequence is always padded up to a multiple of 64 positions. This keeps the number of
        distinct tensor shapes at 8 instead of 512, so the GPU memory cache can reuse its blocks
        (with 512 shapes it grew without limit and, on Windows, spilled into slow shared memory).
        The causal mask means the padding after the current position cannot affect the result.

        Args:
            n: number of grids to draw.
            temperature: below 1 gives safer, blurrier-but-cleaner grids; above 1 more variety and more errors.
            top_k: if set, only the k most likely codes are considered at each step.

        Returns:
            (n, H, W) long tensor of code indices, ready for VQVAE.decode_indices.
        """
        device = next(self.parameters()).device
        L = self.seq_len
        toks = torch.full((n, L), self.num_codes, dtype=torch.long, device=device)   # input: start token, then codes so far
        codes = torch.zeros(n, L, dtype=torch.long, device=device)                    # the sampled grid
        for t in range(L):
            T = min(L, (t // 64 + 1) * 64)                           # padded prefix length (8 distinct values)
            logits = self(toks[:, :T])[:, t] / temperature           # distribution for code t
            if top_k:
                kth = logits.topk(top_k, dim=-1).values[:, -1:]
                logits = logits.masked_fill(logits < kth, float("-inf"))
            nxt = torch.multinomial(F.softmax(logits, dim=-1), 1)[:, 0]
            codes[:, t] = nxt
            if t + 1 < L:
                toks[:, t + 1] = nxt                                 # becomes the input for the next position
        return codes.view(n, *self.grid)
